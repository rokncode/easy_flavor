import 'package:path/path.dart' as p;

import '../config/easy_flavor_config.dart';
import '../core/change_set.dart';
import '../core/exceptions.dart';
import '../core/generator.dart';
import '../core/project_context.dart';
import 'main_dart.dart';
import 'pubspec_editor.dart';
import 'templates.dart';

/// Dart entry points (`lib/flavors.dart`, `lib/main_<flavor>.dart`), the
/// `lib/main.dart` refactor and `default-flavor` in pubspec.yaml.
class DartCodeGenerator implements Generator, Checker {
  const DartCodeGenerator();

  @override
  String get name => 'dart';

  @override
  bool isApplicable(PlanRequest request) => true;

  @override
  Future<void> plan(PlanRequest request) async {
    final changes = request.changes;
    final config = request.config;
    final fallback = defaultFlavor(config);

    final existingFlavors = changes.read(flavorsFile);
    if (existingFlavors != null && !_isGenerated(existingFlavors)) {
      throw ProjectError(
        '$flavorsFile already exists and was not generated by easy_flavor.',
        hint: 'Rename or remove it, then re-run.',
      );
    }
    changes.write(
      flavorsFile,
      renderFlavorsDart(
        config,
        baseUrls: existingFlavors == null
            ? const {}
            : readBaseUrls(existingFlavors),
      ),
      reason: 'Flavor enum and FlavorConfig',
    );

    final main = changes.read(mainFile);
    if (main == null) {
      throw ProjectError(
        '$mainFile not found.',
        hint:
            'easy_flavor needs lib/main.dart to host the shared runMainApp().',
      );
    }
    final refactor = refactorMainDart(main, fallback);
    changes.write(
      mainFile,
      refactor.source,
      reason: 'main() -> runMainApp(), default flavor $fallback',
    );

    for (final f in config.flavorNames) {
      final path = mainEntryFile(f);
      final existing = changes.read(path);
      if (existing != null && !_isGenerated(existing)) {
        throw ProjectError(
          '$path already exists and was not generated by easy_flavor.',
          hint: 'Rename or remove it, then re-run.',
        );
      }
      changes.write(
        path,
        renderMainEntry(
          f,
          awaitRunMainApp: refactor.runMainAppReturnsFuture,
          firebase: config.firebase,
        ),
        reason: 'entry point',
      );
    }

    for (final path in _generatedEntryPoints(request.context, changes)) {
      final flavor = _flavorOfEntry(path);
      if (!config.flavorNames.contains(flavor)) {
        changes.delete(path, reason: 'flavor removed');
      }
    }

    final pubspec = changes.read('pubspec.yaml');
    if (pubspec != null) {
      changes.write(
        'pubspec.yaml',
        withDefaultFlavor(pubspec, fallback),
        reason: 'default-flavor: $fallback',
      );
    }
  }

  static bool _isGenerated(String source) =>
      source.startsWith(generatedDartHeader);

  /// `lib/main_*.dart` files carrying the generated header.
  Iterable<String> _generatedEntryPoints(
    ProjectContext context,
    ChangeSet changes,
  ) sync* {
    final lib = context.dir('lib');
    if (!lib.existsSync()) return;
    for (final entity in lib.listSync()) {
      final rel = p.relative(entity.path, from: context.root);
      if (_flavorOfEntry(rel) == null) continue;
      final content = changes.read(rel);
      if (content != null && _isGenerated(content)) yield rel;
    }
  }

  static String? _flavorOfEntry(String path) =>
      RegExp(r'^lib[/\\]main_(\w+)\.dart$').firstMatch(path)?.group(1);

  @override
  List<Issue> check(ProjectContext context, EasyFlavorConfig config) {
    final issues = <Issue>[];
    final flavors = context.readOrNull(flavorsFile);
    if (flavors == null) {
      issues.add(
        const Issue(
          Severity.error,
          '$flavorsFile is missing.',
          fix: 'Run `easy_flavor init`.',
        ),
      );
    } else if (!RegExp(
      'enum Flavor \\{ ${config.flavorNames.join(', ')} \\}',
    ).hasMatch(flavors)) {
      issues.add(
        const Issue(
          Severity.error,
          '$flavorsFile does not match easy_flavor.yaml.',
          fix: 'Run `easy_flavor init` to regenerate it.',
        ),
      );
    }
    for (final f in config.flavorNames) {
      if (!context.exists(mainEntryFile(f))) {
        issues.add(
          Issue(
            Severity.error,
            '${mainEntryFile(f)} is missing.',
            fix: 'Run `easy_flavor init`.',
          ),
        );
      }
    }
    final main = context.readOrNull(mainFile);
    if (main != null && !main.contains('runMainApp')) {
      issues.add(
        const Issue(
          Severity.error,
          '$mainFile has no runMainApp(); flavor entry points will not compile.',
          fix: 'Run `easy_flavor init`.',
        ),
      );
    }
    final pubspec = context.readOrNull('pubspec.yaml');
    if (pubspec != null) {
      final current = readDefaultFlavor(pubspec);
      if (current != null && !config.flavorNames.contains(current)) {
        issues.add(
          Issue(
            Severity.error,
            'pubspec.yaml default-flavor "$current" is not a configured flavor.',
            fix: 'Run `easy_flavor init`.',
          ),
        );
      }
    }
    return issues;
  }
}
