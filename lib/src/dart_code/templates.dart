/// First line of every Dart file easy_flavor owns; used to recognise files it
/// may overwrite or delete.
const generatedDartHeader = '// Generated by easy_flavor.';

const flavorsFile = 'lib/flavors.dart';

String mainEntryFile(String flavor) => 'lib/main_$flavor.dart';

/// The flavor `lib/main.dart` (and plain `flutter run`) uses: the production
/// flavor if there is one, otherwise the first.
String defaultFlavor(EasyFlavorConfig config) => config.flavors
    .firstWhere(
      (f) => isProductionFlavor(f.name),
      orElse: () => config.flavors.first,
    )
    .name;

String defaultBaseUrl(String flavor) => isProductionFlavor(flavor)
    ? "'https://api.example.com'"
    : "'https://api.$flavor.example.com'";

/// Renders `lib/flavors.dart`. [baseUrls] holds the baseUrl expressions to
/// keep from the previous version of the file, keyed by flavor.
String renderFlavorsDart(
  EasyFlavorConfig config, {
  Map<String, String> baseUrls = const {},
}) {
  final cases = StringBuffer();
  for (final f in config.flavors) {
    cases
      ..writeln('    Flavor.${f.name} => const FlavorConfig._(')
      ..writeln('      flavor: Flavor.${f.name},')
      ..writeln('      appTitle: ${dartString(f.appName)},')
      ..writeln('      baseUrl: ${baseUrls[f.name] ?? defaultBaseUrl(f.name)},')
      ..writeln('    ),');
  }
  return '''
$generatedDartHeader
//
// The Flavor enum and app titles are regenerated from easy_flavor.yaml when
// flavors change. Edits to the `baseUrl:` lines are kept, as long as each
// stays on one line and is a constant expression.

enum Flavor { ${config.flavorNames.join(', ')} }

class FlavorConfig {
  const FlavorConfig._({
    required this.flavor,
    required this.appTitle,
    required this.baseUrl,
  });

  final Flavor flavor;
  final String appTitle;
  final String baseUrl;

  String get name => flavor.name;

  static FlavorConfig? _instance;

  /// The active flavor, set by [init] in the `main_<flavor>.dart` entry points.
  static FlavorConfig get instance =>
      _instance ??
      (throw StateError(
        'FlavorConfig.init() was not called. '
        'Start the app from a lib/main_<flavor>.dart entry point.',
      ));

  static void init(Flavor flavor) => _instance = forFlavor(flavor);

  static FlavorConfig forFlavor(Flavor flavor) => switch (flavor) {
$cases  };
}
''';
}

/// Reads the `baseUrl:` expression of each flavor from a previously
/// generated `lib/flavors.dart`.
Map<String, String> readBaseUrls(String source) {
  final result = <String, String>{};
  final caseLine = RegExp(r'^\s*Flavor\.(\w+)\s*=>');
  final baseUrlLine = RegExp(r'^\s*baseUrl:\s*(.+?),?\s*$');
  String? current;
  for (final line in source.split('\n')) {
    final c = caseLine.firstMatch(line);
    if (c != null) {
      current = c.group(1);
      continue;
    }
    final b = baseUrlLine.firstMatch(line);
    if (b != null && current != null) result[current] = b.group(1)!;
  }
  return result;
}

String firebaseOptionsFile(String flavor) =>
    'lib/firebase/firebase_options_$flavor.dart';

/// Renders `lib/main_<flavor>.dart`. [awaitRunMainApp] must be true when
/// `runMainApp` returns a Future. With [firebase], Firebase is initialised
/// with the flavor's options before the app starts.
String renderMainEntry(
  String flavor, {
  required bool awaitRunMainApp,
  bool firebase = false,
}) {
  final b = StringBuffer()
    ..writeln(generatedDartHeader)
    ..writeln('// flutter run --flavor $flavor -t lib/main_$flavor.dart')
    ..writeln();
  if (firebase) {
    b
      ..writeln("import 'package:firebase_core/firebase_core.dart';")
      ..writeln("import 'package:flutter/widgets.dart';")
      ..writeln()
      ..writeln("import 'firebase/firebase_options_$flavor.dart';");
  }
  b
    ..writeln("import 'flavors.dart';")
    ..writeln("import 'main.dart' show runMainApp;")
    ..writeln()
    ..writeln('Future<void> main() async {');
  if (firebase) b.writeln('  WidgetsFlutterBinding.ensureInitialized();');
  b.writeln('  FlavorConfig.init(Flavor.$flavor);');
  if (firebase) {
    b
      ..writeln('  await Firebase.initializeApp(')
      ..writeln('    options: DefaultFirebaseOptions.currentPlatform,')
      ..writeln('  );');
  }
  b
    ..writeln(awaitRunMainApp ? '  await runMainApp();' : '  runMainApp();')
    ..writeln('}');
  return b.toString();
}

/// A single-quoted Dart string literal for [value].
String dartString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}
