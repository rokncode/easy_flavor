import 'dart:convert';

import 'package:path/path.dart' as p;

import '../config/easy_flavor_config.dart';
import '../core/change_set.dart';
import '../core/generator.dart';
import '../core/project_context.dart';

const launchJsonFile = '.vscode/launch.json';

String androidStudioRunFile(String flavor) => '.run/$flavor.run.xml';

/// `.vscode/launch.json` entries and Android Studio run configurations.
class IdeGenerator implements Generator, Checker {
  const IdeGenerator();

  @override
  String get name => 'ide';

  @override
  bool isApplicable(PlanRequest request) => true;

  @override
  Future<void> plan(PlanRequest request) async {
    final config = request.config;
    _planVsCode(
      request.context,
      request.changes,
      config.ide.contains(IdeTarget.vscode) ? config.flavorNames : const [],
    );
    _planAndroidStudio(
      request.context,
      request.changes,
      config.ide.contains(IdeTarget.androidStudio)
          ? config.flavorNames
          : const [],
    );
  }

  void _planVsCode(
    ProjectContext context,
    ChangeSet changes,
    List<String> flavors,
  ) {
    final source = changes.read(launchJsonFile);
    if (source == null && flavors.isEmpty) return;

    Map<String, Object?> doc;
    var hadComments = false;
    if (source == null) {
      doc = {'version': '0.2.0', 'configurations': <Object?>[]};
    } else {
      final parsed = parseJsonc(source);
      if (parsed == null || parsed.$1 is! Map<String, Object?>) {
        context.logger.warn(
          'Could not parse $launchJsonFile; skipping VS Code configurations.',
        );
        return;
      }
      doc = parsed.$1 as Map<String, Object?>;
      hadComments = parsed.$2;
    }
    final existing = doc['configurations'];
    if (existing is! List<Object?>) {
      context.logger.warn(
        '$launchJsonFile has no "configurations" list; skipping.',
      );
      return;
    }

    final wanted = {for (final f in flavors) f: _vsCodeEntry(f)};
    final result = <Object?>[];
    for (final entry in existing) {
      final flavor = _ownedVsCodeFlavor(entry);
      if (flavor == null) {
        result.add(entry);
      } else if (wanted.containsKey(flavor)) {
        result.add(wanted.remove(flavor));
      }
      // Owned entries for flavors no longer configured are dropped.
    }
    result.addAll(wanted.values);
    if (source == null && result.isEmpty) return;

    doc['configurations'] = result;
    final output = '${const JsonEncoder.withIndent('  ').convert(doc)}\n';
    // Only rewrite when the content changed, so files with comments are not
    // reformatted needlessly.
    if (source != null && jsonEquals(parseJsonc(source)!.$1, doc)) return;
    changes.write(
      launchJsonFile,
      output,
      reason: hadComments
          ? 'flavor launch configs (comments removed)'
          : 'flavor launch configs',
    );
  }

  static Map<String, Object?> _vsCodeEntry(String flavor) => {
    'name': flavor,
    'request': 'launch',
    'type': 'dart',
    'program': 'lib/main_$flavor.dart',
    'args': ['--flavor', flavor],
  };

  /// The flavor of a launch entry easy_flavor generated, or null.
  static String? _ownedVsCodeFlavor(Object? entry) {
    if (entry is! Map) return null;
    final program = entry['program'];
    final args = entry['args'];
    if (program is! String || args is! List) return null;
    final flavor = RegExp(
      r'^lib/main_(\w+)\.dart$',
    ).firstMatch(program)?.group(1);
    if (flavor == null) return null;
    final i = args.indexOf('--flavor');
    return i >= 0 && i + 1 < args.length && args[i + 1] == flavor
        ? flavor
        : null;
  }

  void _planAndroidStudio(
    ProjectContext context,
    ChangeSet changes,
    List<String> flavors,
  ) {
    for (final f in flavors) {
      final path = androidStudioRunFile(f);
      final existing = changes.read(path);
      if (existing != null && !_isOwnedRunConfig(existing, f)) {
        context.logger.warn(
          '$path exists and was not generated by easy_flavor; leaving it.',
        );
        continue;
      }
      changes.write(
        path,
        renderAndroidStudioRunConfig(f),
        reason: 'Android Studio run config',
      );
    }
    final runDir = context.dir('.run');
    if (!runDir.existsSync()) return;
    for (final entity in runDir.listSync()) {
      final match = RegExp(
        r'^(\w+)\.run\.xml$',
      ).firstMatch(p.basename(entity.path));
      final flavor = match?.group(1);
      if (flavor == null || flavors.contains(flavor)) continue;
      final path = androidStudioRunFile(flavor);
      final content = changes.read(path);
      if (content != null && _isOwnedRunConfig(content, flavor)) {
        changes.delete(path, reason: 'flavor removed');
      }
    }
  }

  static bool _isOwnedRunConfig(String content, String flavor) =>
      content.contains('<option name="buildFlavor" value="$flavor" />') &&
      content.contains('lib/main_$flavor.dart');

  @override
  List<Issue> check(ProjectContext context, EasyFlavorConfig config) =>
      const [];
}

String renderAndroidStudioRunConfig(String flavor) =>
    '''
<component name="ProjectRunConfigurationManager">
  <configuration default="false" name="$flavor" type="FlutterRunConfigurationType" factoryName="Flutter">
    <option name="buildFlavor" value="$flavor" />
    <option name="filePath" value="\$PROJECT_DIR\$/lib/main_$flavor.dart" />
    <method v="2" />
  </configuration>
</component>
''';

/// Parses JSON that may contain `//` and `/* */` comments and trailing
/// commas (the JSONC dialect VS Code uses). Returns the value and whether
/// comments were present, or null if it is not valid.
(Object?, bool)? parseJsonc(String source) {
  final b = StringBuffer();
  var hadComments = false;
  var i = 0;
  while (i < source.length) {
    final c = source[i];
    if (c == '"') {
      final start = i++;
      while (i < source.length && source[i] != '"') {
        if (source[i] == r'\') i++;
        i++;
      }
      b.write(source.substring(start, (i + 1).clamp(0, source.length)));
      i++;
    } else if (source.startsWith('//', i)) {
      hadComments = true;
      final end = source.indexOf('\n', i);
      i = end == -1 ? source.length : end;
    } else if (source.startsWith('/*', i)) {
      hadComments = true;
      final end = source.indexOf('*/', i + 2);
      if (end == -1) return null;
      i = end + 2;
    } else {
      b.write(c);
      i++;
    }
  }
  final stripped = b.toString().replaceAllMapped(
    RegExp(r',(\s*[}\]])'),
    (m) => m.group(1)!,
  );
  try {
    return (jsonDecode(stripped), hadComments);
  } on FormatException {
    return null;
  }
}

/// Deep equality for decoded JSON values.
bool jsonEquals(Object? a, Object? b) => jsonEncode(a) == jsonEncode(b);
