import '../config/easy_flavor_config.dart';
import '../core/change_set.dart';
import '../core/generator.dart';
import '../core/project_context.dart';
import 'android_manifest.dart';
import 'android_project.dart';
import 'android_resources.dart';
import 'gradle_file.dart';

/// Gradle productFlavors, app name resources, the manifest label and
/// `src/<flavor>/` folders.
class AndroidGenerator implements Generator, Checker {
  const AndroidGenerator();

  @override
  String get name => 'android';

  @override
  bool isApplicable(PlanRequest request) => request.context.exists('android');

  @override
  Future<void> plan(PlanRequest request) async {
    final context = request.context;
    final changes = request.changes;
    final config = request.config;

    final appName = mainDefinesAppName(context)
        ? AppNameSource.flavorStringsXml
        : AppNameSource.resValue;
    if (appName == AppNameSource.flavorStringsXml) {
      context.logger.detail(
        'main/res/values defines app_name; using per-flavor strings.xml.',
      );
    }

    final gradle = requireAppGradleFile(context, read: changes.read);
    final previousFlavors = gradle.managedFlavors;
    changes.write(
      gradle.path,
      gradle.withFlavors(config.flavors, appName),
      reason: 'productFlavors',
    );

    final manifest = changes.read(manifestFile);
    if (manifest != null) {
      changes.write(
        manifestFile,
        withAppNameLabel(manifest),
        reason: 'label = @string/app_name',
      );
    }

    for (final f in config.flavors) {
      _writeIfMissing(changes, flavorKeepPath(f.name), '', 'flavor source set');
      final strings = flavorStringsPath(f.name);
      if (appName == AppNameSource.flavorStringsXml) {
        if (_isOursOrMissing(changes, strings)) {
          changes.write(
            strings,
            renderFlavorStringsXml(f.appName),
            reason: 'app_name',
          );
        } else {
          context.logger.warn(
            '$strings exists and was not generated by easy_flavor; '
            'make sure it defines app_name.',
          );
        }
      } else if (_isGenerated(changes, strings)) {
        changes.delete(strings, reason: 'app_name now set by resValue');
      }
    }

    // Flavors that were removed from the config. User files in the source
    // set (google-services.json, icons) are kept.
    final current = config.flavorNames.toSet();
    final removed = {
      ...previousFlavors,
      ...?request.previous?.flavorNames,
    }.difference(current);
    for (final name in removed) {
      changes.delete(flavorKeepPath(name), reason: 'flavor removed');
      if (_isGenerated(changes, flavorStringsPath(name))) {
        changes.delete(flavorStringsPath(name), reason: 'flavor removed');
      }
    }
  }

  void _writeIfMissing(
    ChangeSet changes,
    String path,
    String content,
    String reason,
  ) {
    if (changes.read(path) == null) {
      changes.write(path, content, reason: reason);
    }
  }

  bool _isGenerated(ChangeSet changes, String path) =>
      changes.read(path)?.contains(generatedXmlComment) ?? false;

  bool _isOursOrMissing(ChangeSet changes, String path) {
    final content = changes.read(path);
    return content == null || content.contains(generatedXmlComment);
  }

  @override
  List<Issue> check(ProjectContext context, EasyFlavorConfig config) {
    if (!context.exists('android')) return const [];
    final issues = <Issue>[];
    if (context.exists(kotlinBuildFile) && context.exists(groovyBuildFile)) {
      issues.add(
        const Issue(
          Severity.error,
          'Both $kotlinBuildFile and $groovyBuildFile exist.',
          fix: 'Delete the one you no longer use.',
        ),
      );
    }
    final gradle = readAppGradleFile(context);
    if (gradle == null) {
      return [
        ...issues,
        const Issue(Severity.error, 'No Android app build script found.'),
      ];
    }
    final managed = gradle.managedFlavors.toSet();
    final missing = config.flavorNames
        .where((f) => !managed.contains(f))
        .toList();
    final extra = managed.difference(config.flavorNames.toSet());
    if (gradle.managedRange == null) {
      issues.add(
        Issue(
          Severity.error,
          '${gradle.path} has no easy_flavor productFlavors block.',
          fix: 'Run `easy_flavor init`.',
        ),
      );
    } else if (missing.isNotEmpty || extra.isNotEmpty) {
      issues.add(
        Issue(
          Severity.error,
          'Gradle flavors (${managed.join(', ')}) do not match easy_flavor.yaml '
          '(${config.flavorNames.join(', ')}).',
          fix: 'Run `easy_flavor init` to resync.',
        ),
      );
    }
    final unmanaged = gradle.unmanagedFlavors;
    if (unmanaged.isNotEmpty) {
      issues.add(
        Issue(
          Severity.warning,
          'Flavors declared outside easy_flavor: ${unmanaged.join(', ')}.',
        ),
      );
    }
    final manifest = context.readOrNull(manifestFile);
    if (manifest != null && applicationLabel(manifest) != appNameLabel) {
      issues.add(
        const Issue(
          Severity.warning,
          'AndroidManifest.xml label is not @string/app_name, so flavor app names are ignored.',
          fix: 'Run `easy_flavor init`.',
        ),
      );
    }
    return issues;
  }
}
