import 'dart:io';

import 'package:path/path.dart' as p;

import '../core/project_context.dart';

const generatedXmlComment = '<!-- Generated by easy_flavor. Do not edit. -->';

/// `android/app/src/<flavor>/res/values/strings.xml` for the fallback
/// app-name strategy.
String flavorStringsPath(String flavor) =>
    'android/app/src/$flavor/res/values/strings.xml';

/// Placeholder that keeps `android/app/src/<flavor>/` in version control.
String flavorKeepPath(String flavor) => 'android/app/src/$flavor/.gitkeep';

String renderFlavorStringsXml(String appName) =>
    '''
<?xml version="1.0" encoding="utf-8"?>
$generatedXmlComment
<resources>
    <string name="app_name">${androidStringResource(appName)}</string>
</resources>
''';

/// Escapes [value] as Android string resource text.
String androidStringResource(String value) => value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll(r'\', r'\\')
    .replaceAll("'", r"\'")
    .replaceAll('"', r'\"');

/// Whether a values XML file in the main source set defines `app_name`. If
/// so, a flavor resValue with the same name would fail the build with a
/// duplicate resource error.
bool mainDefinesAppName(ProjectContext context) {
  final values = context.dir('android/app/src/main/res/values');
  if (!values.existsSync()) return false;
  final pattern = RegExp(r'''<string\s[^>]*name\s*=\s*["']app_name["']''');
  for (final f in values.listSync().whereType<File>()) {
    if (p.extension(f.path) == '.xml' &&
        pattern.hasMatch(f.readAsStringSync())) {
      return true;
    }
  }
  return false;
}
