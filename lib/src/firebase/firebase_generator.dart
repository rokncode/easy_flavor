const copyPlistPhaseName = '[easy_flavor] Copy GoogleService-Info.plist';

const serviceInfoPlist = 'GoogleService-Info.plist';

String googleServicesJsonPath(String flavor) =>
    'android/app/src/$flavor/google-services.json';

String googleServiceInfoPlistPath(String flavor) =>
    'ios/config/$flavor/GoogleService-Info.plist';

const copyPlistScript = r'''
# Generated by easy_flavor. Copies the GoogleService-Info.plist of the flavor
# being built; EASY_FLAVOR is set in ios/Flutter/<Config>-<flavor>.xcconfig.
PLIST="${PROJECT_DIR}/config/${EASY_FLAVOR}/GoogleService-Info.plist"
if [ -z "${EASY_FLAVOR}" ] || [ ! -f "${PLIST}" ]; then
  echo "error: ${PLIST} not found. Run: easy_flavor init --firebase" >&2
  exit 1
fi
cp "${PLIST}" "${BUILT_PRODUCTS_DIR}/${PRODUCT_NAME}.app/GoogleService-Info.plist"
''';

/// Firebase per flavor: `flutterfire configure` runs (options file and
/// service files) and the iOS build phase that bundles the right plist.
/// Dart entry points get Firebase initialisation from the Dart generator.
class FirebaseGenerator implements Generator, Checker {
  const FirebaseGenerator({this.environment});

  /// Environment for CI credentials; defaults to the process environment.
  final Map<String, String>? environment;

  @override
  String get name => 'firebase';

  // Always runs so it can also remove its build phase when Firebase is
  // turned off.
  @override
  bool isApplicable(PlanRequest request) => true;

  @override
  Future<void> plan(PlanRequest request) async {
    final context = request.context;
    final changes = request.changes;
    final config = request.config;
    final hasIos = changes.read(pbxprojFile) != null;
    final hasAndroid = context.exists('android');

    if (!config.firebase) {
      if (hasIos) {
        _updatePbxproj(changes, (x) => x.removeScriptPhase(copyPlistPhaseName));
      }
      return;
    }

    final missing = [
      for (final f in config.flavors)
        if (f.firebaseProjectId == null) f.name,
    ];
    if (missing.isNotEmpty) {
      throw UsageError(
        'No Firebase project set for: ${missing.join(', ')}.',
        hint:
            'Pass --firebase-projects ${missing.map((f) => '$f=<project-id>').join(',')} '
            'or set firebase_project in ${EasyFlavorConfig.fileName}.',
      );
    }
    await requireFirebaseTools(
      context.processRunner,
      ios: hasIos,
      environment: environment,
    );
    if (hasIos && !Platform.isMacOS) {
      context.logger.warn(
        'flutterfire only writes iOS service files on macOS; '
        're-run on a Mac to finish the iOS Firebase setup.',
      );
    }

    if (!_dependsOnFirebaseCore(changes.read('pubspec.yaml'))) {
      changes.run(
        ExternalCommand(
          'flutter',
          ['pub', 'add', 'firebase_core'],
          reason: 'Firebase dependency',
          mayModify: const ['pubspec.yaml', 'pubspec.lock'],
        ),
      );
    }

    final env = environment ?? Platform.environment;
    for (final f in config.flavors) {
      final previous = request.previous?.flavor(f.name);
      final outputs = [
        firebaseOptionsFile(f.name),
        if (hasAndroid) googleServicesJsonPath(f.name),
        if (hasIos && Platform.isMacOS) googleServiceInfoPlistPath(f.name),
      ];
      final upToDate =
          request.previous?.firebase == true &&
          previous != null &&
          previous.firebaseProjectId == f.firebaseProjectId &&
          previous.androidId == f.androidId &&
          previous.iosBundleId == f.iosBundleId &&
          outputs.every((o) => changes.read(o) != null);
      if (upToDate) continue;
      changes.run(
        ExternalCommand(
          'flutterfire',
          flutterfireArgs(f, android: hasAndroid, ios: hasIos, env: env),
          reason: 'Firebase project ${f.firebaseProjectId} for ${f.name}',
          // flutterfire edits the Xcode project through Ruby; easy_flavor
          // manages it and adds its own copy phase instead.
          preserve: [if (hasIos) pbxprojFile],
          mayModify: [
            ...flutterfireOutputs(f.name, android: hasAndroid, ios: hasIos),
            'firebase.json',
            'android/settings.gradle',
            'android/settings.gradle.kts',
            'android/build.gradle',
            'android/build.gradle.kts',
            'android/app/build.gradle',
            'android/app/build.gradle.kts',
          ],
        ),
      );
    }

    if (hasIos) {
      _updatePbxproj(changes, (x) {
        // A plist already bundled as a resource (the usual single-project
        // Firebase setup) would be produced twice: "Multiple commands
        // produce .../GoogleService-Info.plist".
        for (final path in x.removeBundleResourcesNamed(serviceInfoPlist)) {
          context.logger.info(
            'Removed $path from Copy Bundle Resources; the flavor\'s plist is '
            'copied by the "$copyPlistPhaseName" build phase instead.',
          );
        }
      });
      _updatePbxproj(
        changes,
        (x) => x.setScriptPhase(
          name: copyPlistPhaseName,
          script: copyPlistScript,
          inputPaths: [
            r'$(PROJECT_DIR)/config/$(EASY_FLAVOR)/GoogleService-Info.plist',
          ],
          outputPaths: [
            r'$(BUILT_PRODUCTS_DIR)/$(PRODUCT_NAME).app/GoogleService-Info.plist',
          ],
        ),
      );
    }
  }

  void _updatePbxproj(ChangeSet changes, void Function(XcodeProject) edit) {
    final source = changes.read(pbxprojFile);
    if (source == null) return;
    final xcode = XcodeProject.parse(source);
    edit(xcode);
    changes.write(pbxprojFile, xcode.encode(), reason: 'build configurations');
  }

  static bool _dependsOnFirebaseCore(String? pubspec) {
    if (pubspec == null) return false;
    final deps = (loadYaml(pubspec) as YamlMap?)?['dependencies'];
    return deps is YamlMap && deps.containsKey('firebase_core');
  }

  @override
  List<Issue> check(ProjectContext context, EasyFlavorConfig config) {
    if (!config.firebase) return const [];
    const fix = 'Run `easy_flavor init --firebase`.';
    final hasIos = context.exists(pbxprojFile);
    final issues = <Issue>[
      if (!_dependsOnFirebaseCore(context.readOrNull('pubspec.yaml')))
        const Issue(
          Severity.error,
          'firebase_core is not a dependency.',
          fix: 'Run `flutter pub add firebase_core`.',
        ),
    ];
    for (final f in config.flavors) {
      if (f.firebaseProjectId == null) {
        issues.add(
          Issue(
            Severity.error,
            'No Firebase project set for ${f.name}.',
            fix: 'Set firebase_project in easy_flavor.yaml.',
          ),
        );
      }
      for (final path in [
        firebaseOptionsFile(f.name),
        if (context.exists('android')) googleServicesJsonPath(f.name),
        if (hasIos) googleServiceInfoPlistPath(f.name),
      ]) {
        if (!context.exists(path)) {
          issues.add(Issue(Severity.error, '$path is missing.', fix: fix));
        }
      }
    }
    if (hasIos) {
      final xcode = XcodeProject.parse(context.readOrNull(pbxprojFile)!);
      final bundled = XcodeProject.parse(
        context.readOrNull(pbxprojFile)!,
      ).removeBundleResourcesNamed(serviceInfoPlist);
      if (bundled.isNotEmpty) {
        issues.add(
          Issue(
            Severity.error,
            '${bundled.join(', ')} is in Copy Bundle Resources as well as copied '
            'by the easy_flavor build phase ("Multiple commands produce").',
            fix: fix,
          ),
        );
      }
      if (xcode.scriptPhaseNamed(copyPlistPhaseName) == null) {
        issues.add(
          const Issue(
            Severity.error,
            'The Xcode build phase that copies GoogleService-Info.plist is missing.',
            fix: fix,
          ),
        );
      }
    }
    return issues;
  }
}

/// Files `flutterfire configure` writes for [flavor].
List<String> flutterfireOutputs(
  String flavor, {
  required bool android,
  required bool ios,
}) => [
  firebaseOptionsFile(flavor),
  if (android) googleServicesJsonPath(flavor),
  if (ios) googleServiceInfoPlistPath(flavor),
];

/// Arguments for `flutterfire configure` for one flavor.
List<String> flutterfireArgs(
  FlavorSpec f, {
  required bool android,
  required bool ios,
  Map<String, String> env = const {},
}) => [
  'configure',
  '--yes',
  '--overwrite-firebase-options',
  '--project=${f.firebaseProjectId}',
  '--out=${firebaseOptionsFile(f.name)}',
  '--platforms=${[if (android) 'android', if (ios) 'ios'].join(',')}',
  if (android) ...[
    '--android-package-name=${f.androidId}',
    '--android-out=${googleServicesJsonPath(f.name)}',
  ],
  if (ios) ...[
    '--ios-bundle-id=${f.iosBundleId}',
    '--ios-out=${googleServiceInfoPlistPath(f.name)}',
    '--ios-build-config=Release-${f.name}',
  ],
  ...firebaseCredentialArgs(env),
];
