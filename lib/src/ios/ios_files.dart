import '../config/flavor_spec.dart';
import '../core/exceptions.dart';

const generatedXcconfigHeader = '// Generated by easy_flavor.';
const infoPlistFile = 'ios/Runner/Info.plist';
const podfile = 'ios/Podfile';
const schemesDir = 'ios/Runner.xcodeproj/xcshareddata/xcschemes';
const runnerScheme = '$schemesDir/Runner.xcscheme';

/// Build setting holding the per-flavor display name.
const displayNameSetting = 'APP_DISPLAY_NAME';

/// Build setting holding the flavor name, for build phases (e.g. copying the
/// flavor's GoogleService-Info.plist).
const flavorSetting = 'EASY_FLAVOR';

/// `ios/Flutter/<base>-<flavor>.xcconfig`.
String xcconfigFileName(String base, String flavor) => '$base-$flavor.xcconfig';
String xcconfigPath(String base, String flavor) =>
    'ios/Flutter/${xcconfigFileName(base, flavor)}';

String schemePath(String flavor) => '$schemesDir/$flavor.xcscheme';

/// Xcode configuration settings file for one flavor/configuration.
///
/// It includes the CocoaPods file for this exact configuration (CocoaPods
/// names them after the lowercased configuration) and Flutter's
/// Generated.xcconfig, then sets the flavor's identifiers. The app target's
/// own settings for these keys are removed so this file takes effect.
String renderXcconfig(
  String base,
  FlavorSpec flavor, {
  String podsTarget = 'Runner',
}) {
  final config = '$base-${flavor.name}';
  return '''
$generatedXcconfigHeader Do not edit; change easy_flavor.yaml instead.
#include? "Pods/Target Support Files/Pods-$podsTarget/Pods-$podsTarget.${config.toLowerCase()}.xcconfig"
#include "Generated.xcconfig"

PRODUCT_BUNDLE_IDENTIFIER = ${flavor.iosBundleId}
$displayNameSetting = ${xcconfigValue(flavor.appName)}
$flavorSetting = ${flavor.name}
''';
}

/// Escapes [value] for an xcconfig file, where `//` starts a comment. The
/// empty `$()` substitution breaks the sequence without changing the value.
String xcconfigValue(String value) => value.replaceAll('//', r'/$()/');

/// Points `CFBundleDisplayName` at `$(APP_DISPLAY_NAME)`, adding the key if
/// needed. Returns the new plist and the previous display name, if any.
(String, String?) withDisplayNameSetting(String plist) {
  const ref = '\$($displayNameSetting)';
  final keyed = RegExp(
    r'(<key>CFBundleDisplayName</key>\s*<string>)([^<]*)(</string>)',
  ).firstMatch(plist);
  if (keyed != null) {
    final previous = _xmlUnescape(keyed.group(2)!);
    final updated = plist.replaceRange(
      keyed.start,
      keyed.end,
      '${keyed.group(1)}$ref${keyed.group(3)}',
    );
    return (updated, previous == ref ? null : previous);
  }
  // Insert as the first entry of the top-level dict.
  final dict = RegExp(r'<plist[^>]*>\s*<dict>\n?').firstMatch(plist);
  if (dict == null) {
    throw ProjectError('$infoPlistFile has no top-level <dict>.');
  }
  final indent =
      RegExp(
        r'^([ \t]*)<key>',
        multiLine: true,
      ).firstMatch(plist.substring(dict.end))?.group(1) ??
      '\t';
  return (
    plist.replaceRange(
      dict.end,
      dict.end,
      '$indent<key>CFBundleDisplayName</key>\n$indent<string>$ref</string>\n',
    ),
    null,
  );
}

String _xmlUnescape(String s) => s
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll('&quot;', '"')
    .replaceAll('&apos;', "'")
    .replaceAll('&amp;', '&');

/// A scheme for [flavor]: a copy of Runner.xcscheme whose actions use the
/// flavor's configurations.
String renderScheme(String runnerSchemeXml, String flavor) =>
    runnerSchemeXml.replaceAllMapped(
      RegExp(r'buildConfiguration\s*=\s*"(Debug|Release|Profile)"'),
      (m) => 'buildConfiguration = "${m.group(1)}-$flavor"',
    );

/// Whether [schemeXml] is a flavor scheme easy_flavor generated for [flavor].
bool isFlavorScheme(String schemeXml, String flavor) =>
    schemeXml.contains('buildConfiguration = "Debug-$flavor"');

/// Rewrites the `project 'Runner', { ... }` map in a Podfile so every
/// configuration in [configurations] is listed, with Debug* mapped to
/// `:debug` and everything else to `:release`.
///
/// Existing entries keep their order (and their mapping, if the user changed
/// it); `<base>-<flavor>` entries for configurations that no longer exist are
/// dropped; missing configurations are appended.
String withPodfileConfigurations(String source, List<String> configurations) {
  final start = RegExp(
    r"""^project\s+['"]Runner['"]\s*,\s*\{""",
    multiLine: true,
  ).firstMatch(source);
  if (start == null) {
    // No mapping: add one after the platform line (or at the top).
    final platform = RegExp(
      r'^#?\s*platform\s*:ios.*\n',
      multiLine: true,
    ).firstMatch(source);
    final at = platform?.end ?? 0;
    return source.replaceRange(
      at,
      at,
      '\n${_podfileMap([for (final c in configurations) (c, _podType(c))])}\n',
    );
  }
  final end = source.indexOf('}', start.end);
  if (end == -1) throw ProjectError('Unterminated project map in $podfile.');
  final existing = RegExp(r"""['"]([^'"]+)['"]\s*=>\s*:(\w+)""")
      .allMatches(source.substring(start.end, end))
      .map((m) => (m.group(1)!, m.group(2)!))
      .toList();
  final entries = [
    for (final e in existing)
      if (configurations.contains(e.$1) ||
          !RegExp(r'^(Debug|Release|Profile)-').hasMatch(e.$1))
        e,
  ];
  final listed = {for (final e in entries) e.$1};
  entries.addAll([
    for (final c in configurations)
      if (!listed.contains(c)) (c, _podType(c)),
  ]);
  final updated = _podfileMap(entries);
  if (source.substring(start.start, end + 1) == updated) return source;
  return source.replaceRange(start.start, end + 1, updated);
}

String _podType(String configuration) =>
    configuration.startsWith('Debug') ? 'debug' : 'release';

String _podfileMap(List<(String, String)> entries) {
  final b = StringBuffer("project 'Runner', {\n");
  for (final (name, type) in entries) {
    b.writeln("  '$name' => :$type,");
  }
  b.write('}');
  return b.toString();
}
