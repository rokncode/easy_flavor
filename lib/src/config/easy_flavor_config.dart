import 'package:meta/meta.dart';
import 'package:yaml/yaml.dart';

import '../core/exceptions.dart';
import 'flavor_spec.dart';

/// In-memory form of `easy_flavor.yaml`.
@immutable
class EasyFlavorConfig {
  const EasyFlavorConfig({
    required this.flavors,
    this.firebase = false,
    this.ide = IdeTarget.values,
    this.mergeExisting = false,
  });

  static const fileName = 'easy_flavor.yaml';

  /// Flavors in declaration order (order matters for generated enums, schemes
  /// and launch configurations).
  final List<FlavorSpec> flavors;
  final bool firebase;

  /// IDE run configurations to generate.
  final List<IdeTarget> ide;

  /// The project had its own flavor setup when easy_flavor was added
  /// (`init --merge`); easy_flavor configures those flavors on top of the
  /// existing Gradle/Xcode setup instead of refusing to touch them.
  final bool mergeExisting;

  List<String> get flavorNames => [for (final f in flavors) f.name];

  FlavorSpec? flavor(String name) {
    for (final f in flavors) {
      if (f.name == name) return f;
    }
    return null;
  }

  EasyFlavorConfig copyWith({
    List<FlavorSpec>? flavors,
    bool? firebase,
    List<IdeTarget>? ide,
    bool? mergeExisting,
  }) => EasyFlavorConfig(
    flavors: flavors ?? this.flavors,
    firebase: firebase ?? this.firebase,
    ide: ide ?? this.ide,
    mergeExisting: mergeExisting ?? this.mergeExisting,
  );

  /// Parses `easy_flavor.yaml` content. Missing per-flavor fields are allowed
  /// here and filled in later by the resolver, so values are nullable in
  /// [PartialFlavor].
  static PartialConfig parse(String source, {String? sourceUrl}) {
    final Object? doc;
    try {
      doc = loadYaml(
        source,
        sourceUrl: sourceUrl == null ? null : Uri.file(sourceUrl),
      );
    } on YamlException catch (e) {
      throw UsageError('Invalid $fileName: ${e.message}');
    }
    if (doc == null) return const PartialConfig();
    if (doc is! YamlMap) throw UsageError('$fileName must be a YAML map.');

    final firebase = doc['firebase'];
    if (firebase != null && firebase is! bool) {
      throw UsageError('$fileName: "firebase" must be true or false.');
    }

    final flavorsNode = doc['flavors'];
    final flavors = <PartialFlavor>[];
    if (flavorsNode != null) {
      if (flavorsNode is! YamlMap) {
        throw UsageError(
          '$fileName: "flavors" must be a map of flavor name to settings.',
        );
      }
      for (final entry in flavorsNode.entries) {
        final name = entry.key.toString();
        final value = entry.value;
        if (value != null && value is! YamlMap) {
          throw UsageError('$fileName: flavor "$name" must be a map.');
        }
        String? field(String key) => (value as YamlMap?)?[key]?.toString();
        flavors.add(
          PartialFlavor(
            name: name,
            appName: field('app_name'),
            androidId: field('android_id'),
            iosBundleId: field('ios_bundle_id'),
            firebaseProjectId: field('firebase_project'),
          ),
        );
      }
    }
    final ideNode = doc['ide'];
    List<IdeTarget>? ide;
    if (ideNode != null) {
      if (ideNode is! YamlList) {
        throw UsageError(
          '$fileName: "ide" must be a list, e.g. [vscode, android-studio].',
        );
      }
      ide = [for (final v in ideNode) IdeTarget.parse(v.toString())];
    }

    final merge = doc['merge_existing'];
    if (merge != null && merge is! bool) {
      throw UsageError('$fileName: "merge_existing" must be true or false.');
    }

    return PartialConfig(
      flavors: flavors,
      firebase: firebase as bool?,
      ide: ide,
      mergeExisting: merge as bool?,
      hasFlavorList: flavors.isNotEmpty,
    );
  }

  /// Serialises to YAML. The output round-trips through [parse].
  String toYaml() {
    final b = StringBuffer()
      ..writeln('# Generated by easy_flavor. Safe to edit; re-run')
      ..writeln('# `easy_flavor init` to apply changes.')
      ..writeln('flavors:');
    for (final f in flavors) {
      b.writeln('  ${f.name}:');
      f.toMap().forEach(
        (k, v) => b.writeln('    $k: ${_scalar(v.toString())}'),
      );
    }
    b.writeln('firebase: $firebase');
    b.writeln('ide: [${ide.map((t) => t.id).join(', ')}]');
    if (mergeExisting) b.writeln('merge_existing: true');
    return b.toString();
  }

  static String _scalar(String v) {
    final plain = RegExp(r'^[A-Za-z0-9._-]+$');
    if (plain.hasMatch(v) &&
        !const {
          'true',
          'false',
          'null',
          'yes',
          'no',
        }.contains(v.toLowerCase())) {
      return v;
    }
    return '"${v.replaceAll(r'\', r'\\').replaceAll('"', r'\"')}"';
  }
}

/// Flavor settings where any field may be missing (from YAML or flags).
@immutable
class PartialFlavor {
  const PartialFlavor({
    required this.name,
    this.appName,
    this.androidId,
    this.iosBundleId,
    this.firebaseProjectId,
  });

  final String name;
  final String? appName;
  final String? androidId;
  final String? iosBundleId;
  final String? firebaseProjectId;

  /// Fields set on [other] win.
  PartialFlavor merge(PartialFlavor other) => PartialFlavor(
    name: name,
    appName: other.appName ?? appName,
    androidId: other.androidId ?? androidId,
    iosBundleId: other.iosBundleId ?? iosBundleId,
    firebaseProjectId: other.firebaseProjectId ?? firebaseProjectId,
  );
}

@immutable
class PartialConfig {
  const PartialConfig({
    this.flavors = const [],
    this.firebase,
    this.hasFlavorList = false,
    this.ide,
    this.mergeExisting,
  });

  final List<PartialFlavor> flavors;
  final bool? firebase;
  final List<IdeTarget>? ide;
  final bool? mergeExisting;

  /// True when [flavors] is an authoritative list (`--flavors` was passed),
  /// rather than just per-flavor overrides.
  final bool hasFlavorList;

  bool get isEmpty =>
      flavors.isEmpty &&
      firebase == null &&
      ide == null &&
      mergeExisting == null;
}

enum IdeTarget {
  vscode('vscode'),
  androidStudio('android-studio');

  const IdeTarget(this.id);

  /// Name used in flags and YAML.
  final String id;

  static IdeTarget parse(String id) {
    for (final t in values) {
      if (t.id == id) return t;
    }
    throw UsageError(
      'Unknown IDE "$id".',
      hint: 'Use one of: ${values.map((t) => t.id).join(', ')}.',
    );
  }
}
